"""``uv run python -m opennaksha.schema`` — regenerate docs/catalog-schema.md from the models."""

from __future__ import annotations

import json
import sys
from pathlib import Path

from opennaksha.models import SCHEMA_VERSION, CatalogIndex, ChangesFile, CityFile

DOC = Path(__file__).resolve().parents[2] / "docs" / "catalog-schema.md"

INTRO = f"""# Catalog schema (version {SCHEMA_VERSION})

Generated by `uv run python -m opennaksha.schema` from `pipeline/opennaksha/models.py`.
Do not edit the JSON Schema blocks by hand.

Published files (compact JSON, UTF-8), relative to the catalog base URL:

| File | Model |
|---|---|
| `catalog/index.json` | `CatalogIndex` |
| `catalog/cities/{{city_id}}.json` | `CityFile` (all schemes of one city, sorted) |
| `catalog/changes.json` | `ChangesFile` (last 20 runs that had changes or failures, newest first) |
| `catalog/status.json` | pipeline bookkeeping (source health), not used by the app |
| `overlays/{{scheme_id}}.png` | overlay image; `overlay.url` holds this relative path |

Rules (PLAN.md §5):

- `id` = `{{city_id}}-{{type}}-{{scheme_no}}`, lowercase, spaces/slashes → dashes.
- Schemes are never deleted; `removed_from_source: true` when gone from the site. A scheme that
  comes back is reported as a `status` change.
- A changed file (new sha256) keeps its old entry with `superseded: true`. A file that is no
  longer listed on the site is also marked `superseded`.
- `overlay.status` becomes `outdated` when no current map file has `overlay.source_sha256`.
- `overlay.corners` = `[[lon,lat] top-left, top-right, bottom-right, bottom-left]`.
- `schema_version` only increases for breaking changes. Optional fields may be added any time
  (apps must ignore unknown keys).
- Timestamps are UTC ISO-8601 (`2026-11-15T02:00:00Z`); `status_date` is a date (`2024-03-12`).
"""


def render() -> str:
    parts = [INTRO]
    for title, model in (
        ("index.json", CatalogIndex),
        ("cities/{city_id}.json", CityFile),
        ("changes.json", ChangesFile),
    ):
        schema = model.model_json_schema(mode="serialization")
        parts.append(f"## `{title}`\n\n```json\n{json.dumps(schema, indent=2)}\n```\n")
    return "\n".join(parts)


def main() -> int:
    DOC.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
